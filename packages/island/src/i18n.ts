function fill(text: string, args: readonly (string | number)[]): string {
  return args.length ? text.replace(/\{(\d)\}/g, (m, i: string) => String(args[Number(i)] ?? m)) : text;
}

/**
 * The text in the island's language. `ru` is a key of EN (or any other string, which stays as is:
 * live data such as track names and already translated captions pass through untouched).
 */
export function tr(s: { lang: Lang }, ru: string, ...args: (string | number)[]): string {
  return fill(s.lang === 'en' ? (EN[ru] ?? ru) : ru, args);
}

/** English plural for a count: "1 commit", "2 commits"; Russian keeps its own forms at the call site */
export function plural(n: number, one: string, many: string): string {
  return n === 1 ? one : many;
}
